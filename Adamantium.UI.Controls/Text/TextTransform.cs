namespace Adamantium.UI.Controls.Text;

/// <summary>The case text is shown in, as CSS's <c>text-transform</c>: the text itself stays as it is.</summary>
public enum TextTransform
{
    /// <summary>As it is.</summary>
    None,

    /// <summary>In upper case.</summary>
    Uppercase,

    /// <summary>In lower case.</summary>
    Lowercase
}
