using System;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Adamantium.UI.Markup.Localization;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;

namespace Adamantium.UI.Generators.Scenarios;

/// <summary>Writes the scenarios of a project as one NUnit fixture, <c>Scenarios</c>, a test a scenario: each starts the
/// application afresh, runs the steps and closes it. The fixture is in the category <c>Scenario</c> - the tests need a
/// desktop and a GPU - and runs one test at a time.</summary>
public static class ScenarioTestEmitter
{
    public static void Emit(SourceProductionContext output, ImmutableArray<ScenarioFile> files, string rootNamespace, string application,
        bool testable)
    {
        if (files.IsEmpty)
        {
            return;
        }

        if (!testable)
        {
            output.ReportDiagnostic(Create("AUS010", MarkupMessages.ScenarioNotInTestProject(), Location.None));
            return;
        }

        if (string.IsNullOrEmpty(rootNamespace))
        {
            output.ReportDiagnostic(Create("AUS000", MarkupMessages.NoRootNamespace(), Location.None));
            return;
        }

        if (string.IsNullOrEmpty(application))
        {
            output.ReportDiagnostic(Create("AUS009", MarkupMessages.ScenarioNoApplication(), Location.None));
            return;
        }

        foreach (var file in files)
        {
            foreach (var problem in file.Problems)
            {
                output.ReportDiagnostic(Create(problem.Id, problem.Message, At(file.Path, problem.Line, problem.Column)));
            }
        }

        var usable = files.Where(file => file.Problems.Count == 0).OrderBy(file => file.Path, StringComparer.Ordinal).ToList();
        foreach (var taken in usable.GroupBy(file => file.Name).Where(group => group.Count() > 1))
        {
            var first = taken.First();
            foreach (var other in taken.Skip(1))
            {
                output.ReportDiagnostic(Create("AUS008", MarkupMessages.ScenarioNameTaken(other.Name, first.Path), At(other.Path, other.NameLine, 1)));
            }
        }

        output.AddSource("Scenarios.g.cs", $$"""
            // <auto-generated/>
            namespace {{rootNamespace}};

            [global::NUnit.Framework.TestFixture]
            [global::NUnit.Framework.Category("Scenario")]
            [global::NUnit.Framework.NonParallelizable]
            public sealed partial class Scenarios
            {
            }
            """);

        foreach (var file in usable.GroupBy(file => file.Name).Select(group => group.First()))
        {
            var test = new StringBuilder();
            test.AppendLine("// <auto-generated/>")
                .AppendLine($"namespace {rootNamespace};")
                .AppendLine()
                .AppendLine("public sealed partial class Scenarios")
                .AppendLine("{")
                .AppendLine("    [global::NUnit.Framework.Test]");
            if (file.Description != null)
            {
                test.AppendLine($"    [global::NUnit.Framework.Description({SymbolDisplay.FormatLiteral(file.Description, true)})]");
            }

            if (file.ExplicitReason != null)
            {
                test.AppendLine($"    [global::NUnit.Framework.Explicit({SymbolDisplay.FormatLiteral(file.ExplicitReason, true)})]");
            }

            test.AppendLine($"    public async global::System.Threading.Tasks.Task {file.Name}()")
                .AppendLine("    {")
                .AppendLine("        await using var session = await global::Adamantium.UI.Automation.AutomationSession.LaunchAsync(")
                .AppendLine("            global::System.IO.Path.Combine(global::System.AppContext.BaseDirectory,")
                .AppendLine($"                global::System.OperatingSystem.IsWindows() ? {SymbolDisplay.FormatLiteral(application + ".exe", true)} : " +
                            $"{SymbolDisplay.FormatLiteral(application, true)}),")
                .AppendLine("            new global::Adamantium.UI.Automation.LaunchOptions { FreshData = true });");
            foreach (var step in file.Steps)
            {
                test.AppendLine($"        {step.Replace("\n", "\n        ")}");
            }

            test.AppendLine("#line default").AppendLine("    }").AppendLine("}");
            output.AddSource($"Scenarios.{file.Name}.g.cs", test.ToString());
        }
    }

    private static Location At(string path, int line, int column)
    {
        var position = new LinePosition(Math.Max(0, line - 1), Math.Max(0, column - 1));
        return Location.Create(path, new TextSpan(0, 0), new LinePositionSpan(position, position));
    }

    private static Diagnostic Create(string id, string message, Location location) =>
        Diagnostic.Create(id, "Scenario", message, DiagnosticSeverity.Error, DiagnosticSeverity.Error, true, 0, location: location);
}
