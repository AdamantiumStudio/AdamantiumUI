namespace Adamantium.UI.Core.Media;

/// <summary>Capital forms of text.</summary>
public enum FontCapitals
{
    Normal,

    /// <summary>Lowercase letters as small capitals (<c>smcp</c>).</summary>
    SmallCaps,

    /// <summary>Every letter as a small capital (<c>smcp</c> and <c>c2sc</c>).</summary>
    AllSmallCaps,

    /// <summary>Lowercase letters as petite capitals (<c>pcap</c>).</summary>
    PetiteCaps,

    /// <summary>Every letter as a petite capital (<c>pcap</c> and <c>c2pc</c>).</summary>
    AllPetiteCaps,

    /// <summary>One height for upper and lower case (<c>unic</c>).</summary>
    Unicase,

    /// <summary>Capitals drawn for large sizes (<c>titl</c>).</summary>
    Titling,
}
