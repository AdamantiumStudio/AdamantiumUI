using System.Runtime.CompilerServices;
using System.Runtime.InteropServices;
using QuantumBinding.Generator;
using QuantumBinding.Generator.CodeGeneration;
using QuantumBinding.Generator.Processors;

namespace Adamantium.UI.BindingGenerator.Cef;

/// <summary>Generates Adamantium.UI.WebView/Generated from the C API of the Chromium Embedded Framework (native: libcef),
/// read as C at the API version the WebView is built against: the common API once, the same on every platform, and
/// what each platform's header declares beside it in its own namespace.</summary>
public sealed class CefBindingGenerator : QuantumBindingGenerator
{
    /// <summary>The CEF API version the bindings are read at: CEF 156's.</summary>
    public const int ApiVersion = 15600;

    private const string Namespace = "Adamantium.UI.WebView.Cef";

    private const string ThreadHeader = "cef_thread_internal";

    private const string FileHeader = """
        ----------------------------------------------------------------------------------------------
        <auto-generated>
        This file was generated by Adamantium.UI.BindingGenerator from the C API headers of the Chromium Embedded
        Framework in native/cef, whose documentation it carries: Copyright (c) Marshall A. Greenblatt, portions
        copyright Google Inc., under the BSD 3-Clause licence in native/cef/LICENSE.txt.
        Do not edit this file manually because you will lose all your changes after the next generation.
        </auto-generated>
        ----------------------------------------------------------------------------------------------
        """;

    private static readonly (TargetPlatform Platform, IReadOnlySet<string> Headers)[] Platforms =
    [
        (TargetPlatform.Windows, new HashSet<string> { "cef_types_win", ThreadHeader }),
        (TargetPlatform.Linux, new HashSet<string> { "cef_types_linux", ThreadHeader }),
        (TargetPlatform.MacOS, new HashSet<string> { "cef_types_mac", ThreadHeader }),
    ];

    private readonly List<Module> modules = [];
    private Module common;

    public override void OnSetup(BindingOptions options)
    {
        options.GenerateSequentialLayout = true;
        options.PodTypesAsSimpleTypes = false;
        options.DebugMode = false;

        var generated = Path.Combine(ProjectDirectory(), "Generated");

        common = CreateModule(TargetPlatform.Windows, "Cef");
        common.InteropSubNamespace = "Interop";
        common.MethodClassName = "CefNative";
        common.InteropClassName = "CefInterop";
        common.OutputPath = Path.Combine(generated, "Common");
        options.AddModule(common);

        foreach (var (platform, _) in Platforms)
        {
            var module = CreateModule(platform, $"Cef.{platform}");
            module.InteropSubNamespace = $"Interop.{platform}";
            module.MethodClassName = $"Cef{platform}Native";
            module.InteropClassName = $"Cef{platform}Interop";
            module.OutputPath = Path.Combine(generated, platform.ToString());
            modules.Add(module);
            options.AddModule(module);
        }
    }

    public override void OnSetupPostProcessing(ProcessingContext context)
    {
        context.AddPreGeneratorPass(new CefCommonApiPass(Platforms[0].Headers), ExecutionPassKind.PerTranslationUnit, common);
        AddNamingPasses(context, common);

        for (var i = 0; i < Platforms.Length; i++)
        {
            context.AddPreGeneratorPass(new CefPlatformOnlyPass(Platforms[i].Headers), ExecutionPassKind.PerTranslationUnit, modules[i]);
            AddNamingPasses(context, modules[i]);
        }
    }

    private static Module CreateModule(TargetPlatform platform, string name)
    {
        var source = SourceDirectory();
        var cef = Path.Combine(ProjectDirectory(), "native", "cef");

        var module = Module.Create("libcef");
        module.Name = name;
        module.SourceLanguage = SourceLanguage.C;
        module.FailOnParseErrors = true;
        module.UseHostSystemHeaders = false;
        module.FileHeader = FileHeader;
        module.TargetPlatform = platform;
        module.GeneratorMode = GeneratorMode.Preview;
        module.EachTypeInSeparateFile = true;
        module.CleanPreviousGeneration = true;
        module.Files.Add(Path.Combine(source, "cef_c_api.h"));
        module.IncludeDirs.Add(Path.Combine(source, "Stubs"));
        module.IncludeDirs.Add(Path.Combine(cef, platform.ToString().ToLowerInvariant()));
        module.IncludeDirs.Add(cef);
        module.Defines.Add($"CEF_API_VERSION={ApiVersion}");
        module.ForceCallingConvention = true;
        module.CallingConvention = CallingConvention.Winapi;
        module.GeneratorSpecializations = GeneratorSpecializations.Enums | GeneratorSpecializations.Structs |
                                          GeneratorSpecializations.Unions | GeneratorSpecializations.Functions;
        module.OutputFileName = $"Adamantium.UI.WebView.{name}";
        module.OutputNamespace = Namespace;
        module.TargetRuntime = TargetRuntime.Net8Plus;
        return module;
    }

    private static void AddNamingPasses(ProcessingContext context, Module module)
    {
        context.AddPreGeneratorPass(new CheckFlagsEnumsPass(), ExecutionPassKind.PerTranslationUnit, module);
        context.AddPreGeneratorPass(new EnumItemsCleanupPass(), ExecutionPassKind.PerTranslationUnit, module);
        context.AddPreGeneratorPass(new EnumItemsRenamePass(CasePattern.PascalCase), ExecutionPassKind.PerTranslationUnit, module);

        var types = RenameTargets.Enum | RenameTargets.Struct | RenameTargets.Union | RenameTargets.Class;
        var renameItems = new[]
        {
            new RegexRenameRunItem("_t$", string.Empty, types, false),
        };
        context.AddPreGeneratorPass(new SequentialRegexRenamePass(renameItems), ExecutionPassKind.PerTranslationUnit, module);
        context.AddPreGeneratorPass(new CaseRenamePass(types | RenameTargets.Field | RenameTargets.Function, CasePattern.PascalCase),
            ExecutionPassKind.PerTranslationUnit, module);
    }

    private static string ProjectDirectory()
    {
        return Path.GetFullPath(Path.Combine(SourceDirectory(), "..", "..", "Adamantium.UI.WebView"));
    }

    private static string SourceDirectory([CallerFilePath] string path = "")
    {
        return Path.GetDirectoryName(path);
    }
}
